# words.json -> src/videos/mandel/captions.ts (caption groups the composition renders).
# One word at a time; a very short word (1-2 letters, not a number) joins the next word when that word follows within
# 0.3 s, and a word shown for under 0.12 s joins the next, so groups are at most 2-3 words. Each group shows from its first word's onset until the next group's onset
# (hard swap), or until 0.35 s after its last word ends when a pause follows. Numbers are digits (words.json "cap").
# Usage: python captions_ts.py words.json ../../src/videos/mandel/captions.ts
import json, sys

w = [x for x in json.load(open(sys.argv[1], encoding="utf-8")) if x["cap"]]
groups = []
i = 0
while i < len(w):
    g = [w[i]]
    while len(g) < 3 and i + 1 < len(w) and (
            (len(g[-1]["cap"].strip(".,?!")) <= 2 and not g[-1]["cap"][0].isdigit() and g[-1]["cap"][-1] not in ".,?!" and w[i + 1]["s"] - g[-1]["e"] < 0.3)
            or w[i + 1]["s"] - g[-1]["s"] < 0.12):  # a word that would flash for under 4 frames joins the next
        i += 1
        g.append(w[i])
    groups.append(g)
    i += 1
out = []
for k, g in enumerate(groups):
    s = g[0]["s"]
    nxt = groups[k + 1][0]["s"] if k + 1 < len(groups) else g[-1]["e"] + 0.6
    e = min(nxt, g[-1]["e"] + 0.35)
    out.append((round(s, 3), round(e, 3), " ".join(x["cap"] for x in g)))
with open(sys.argv[2], "w", encoding="utf-8") as fh:
    fh.write("// Generated by mandel-short/voice/captions_ts.py from words.json: [start s, end s, text]. Do not edit.\n")
    fh.write("export const CAPTIONS: [number, number, string][] = [\n")
    for s, e, t in out:
        fh.write(f"  [{s}, {e}, {json.dumps(t)}],\n")
    fh.write("];\n")
print(len(out), "groups; first:", out[:6])
